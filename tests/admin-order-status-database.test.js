const {PGlite}=require('../.review-tools/node_modules/@electric-sql/pglite');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const db=new PGlite();
(async()=>{
  await db.exec(`create role anon; create role authenticated;
    create function public.is_admin() returns boolean language sql stable as $$select current_setting('test.admin',true)='yes'$$;
    create table public.orders(id int primary key,status text,total numeric,updated_at timestamptz);
    insert into orders values(1,'new',850,now());
    alter table orders enable row level security;
    create policy orders_select on orders for select using(true);
    create policy orders_admin_update on orders for update using(public.is_admin());
    grant usage on schema public to anon,authenticated;
    grant select on orders to anon,authenticated;
    set role authenticated;
    select set_config('test.admin','yes',false);`);
  await assert.rejects(db.query("update orders set status='baking' where id=1"),/permission denied/);
  await db.exec('reset role');
  const fix=fs.readFileSync(path.join(__dirname,'../supabase/admin-order-status.sql'),'utf8');
  await db.exec(fix); await db.exec(fix);
  await db.exec('set role authenticated');
  assert.equal((await db.query("update orders set status='baking',updated_at=now() where id=1 returning status")).rows[0].status,'baking');
  await assert.rejects(db.query('update orders set total=1 where id=1'),/permission denied/);
  await db.exec("select set_config('test.admin','no',false)");
  assert.equal((await db.query("update orders set status='delivered' where id=1 returning id")).rows.length,0);
  await db.exec('reset role; set role anon');
  await assert.rejects(db.query("update orders set status='delivered' where id=1"),/permission denied/);
  await db.exec('reset role');
  assert.equal((await db.query('select status,total from orders')).rows[0].status,'baking');
  console.log('Admin status change succeeds; customer, guest and total edits remain blocked.');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>db.close());
