const {PGlite}=require('../.review-tools/node_modules/@electric-sql/pglite');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const db=new PGlite();
(async()=>{
  await db.exec(`create role anon; create role authenticated;
    grant usage on schema public to authenticated,anon;
    create function public.is_admin() returns boolean language sql stable as $$select current_setting('test.admin',true)='yes'$$;
    create schema vault; create table vault.decrypted_secrets(name text,decrypted_secret text);
    create schema net; create table net._http_response(id bigint,status_code int);
    create table net.requests(id bigserial,body jsonb,headers jsonb);
    create function net.http_post(url text,body jsonb,headers jsonb,timeout_milliseconds int) returns bigint language sql as $$insert into net.requests(body,headers) values(body,headers) returning id$$;
    create schema cron; create function cron.schedule(text,text,text) returns bigint language sql as $$select 1::bigint$$;
    create table public.orders(id uuid primary key,created_at timestamptz default now(),guest_name text,guest_phone text,guest_email text,delivery_address text,notes text,subtotal numeric default 100,discount numeric default 0,delivery_fee numeric default 80,total numeric default 180,estimated_ready_at timestamptz);
    create table public.order_items(order_id uuid,product_name text,qty int,line_total numeric);`);
  const migration=fs.readFileSync(path.join(__dirname,'../supabase/order-email-notifications.sql'),'utf8').replace(/^create extension.*$/gm,'');
  await db.exec(migration);await db.exec(migration);
  await db.exec("insert into orders(id) values('00000000-0000-0000-0000-000000000001')");
  assert.equal((await db.query('select * from order_email_outbox')).rows.length,0);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from order_email_settings')).rows.length,0);
  assert.equal((await db.query('update order_email_settings set enabled=true returning id')).rows.length,0);
  await assert.rejects(db.query('select order_email_ready()'),/Admin access/);
  await assert.rejects(db.query('select bakery_private.send_order_emails()'),/permission denied/);
  await db.exec("select set_config('test.admin','yes',false)");
  assert.equal((await db.query('select * from order_email_settings')).rows.length,1);
  await db.exec('update order_email_settings set enabled=true; reset role');
  const order='00000000-0000-0000-0000-000000000002';
  await db.query('insert into orders(id,guest_name,delivery_address) values($1,$2,$3)',[order,'Test customer','Delivery pin: https://www.google.com/maps?q=7,125']);
  await db.query('insert into order_items values($1,$2,2,100)',[order,'Chiffon Cake']);
  await db.exec('select bakery_private.send_order_emails()');
  assert.equal((await db.query('select * from net.requests')).rows.length,0,'No credentials means no sends');
  await db.exec("insert into vault.decrypted_secrets values('order_email_resend_api_key','test-only'); select bakery_private.send_order_emails()");
  let rows=(await db.query('select * from net.requests')).rows;
  assert.equal(rows.length,1);assert.match(rows[0].body.text,/Chiffon Cake x 2/);assert.match(rows[0].body.text,/google.com\/maps/);
  assert.equal(rows[0].body.to[0],'samalbakes@gmail.com');
  await db.exec('select bakery_private.send_order_emails()');
  assert.equal((await db.query('select * from net.requests')).rows.length,1,'In-flight sends are not duplicated');
  await db.exec('insert into net._http_response values(1,500); select bakery_private.send_order_emails()');
  assert.equal((await db.query('select state from order_email_outbox')).rows[0].state,'pending');
  await db.exec("update order_email_outbox set last_attempt_at=now()-interval '6 minutes'; select bakery_private.send_order_emails()");
  rows=(await db.query('select * from net.requests order by id')).rows;
  assert.equal(rows.length,2);assert.deepEqual(rows[0].body,rows[1].body);assert.equal(rows[0].headers['Idempotency-Key'],rows[1].headers['Idempotency-Key']);
  await db.exec('insert into net._http_response values(2,200); select bakery_private.send_order_emails()');
  assert.equal((await db.query('select state from order_email_outbox')).rows[0].state,'accepted');
  await db.exec('set role authenticated');
  await assert.rejects(db.query("update order_email_outbox set state='pending'"),/permission denied/);
  await db.exec('reset role');
  console.log('Email queue tests pass: disabled default, admin-only settings, credential gating, committed items and map links, in-flight duplicate prevention, immutable idempotent retries and acceptance.');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>db.close());
